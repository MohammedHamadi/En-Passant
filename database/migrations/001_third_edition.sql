create function public.ep_snapshot() returns jsonb language sql stable security definer set search_path=public,pg_temp as $$
 select jsonb_build_object('revision',s.revision,'settings',s.value,
   'players',coalesce((select jsonb_agg(to_jsonb(p)-'elo'-'is_active'-'is_present' order by p.id) from public.players p),'[]'),
   'rounds',coalesce((select jsonb_agg(to_jsonb(r) order by r.number) from public.rounds r),'[]'),
   'games',coalesce((select jsonb_agg(to_jsonb(g) order by g.id) from public.games g),'[]'))
 from public.tournament_settings s where singleton;
$$;

-- The service calculates a proposed state; this function atomically compares and commits it.
-- One revision lock serializes capacity checks, code/email uniqueness, and round generation.
create function public.ep_commit(p_expected bigint,p_state jsonb,p_actor text,p_action text)
returns bigint language plpgsql security definer set search_path=public,pg_temp as $$
declare old_state jsonb; actual bigint; p record;
begin
  select revision into actual from public.tournament_settings where singleton for update;
  if actual<>p_expected then raise exception 'STALE_REVISION' using errcode='40001'; end if;
  old_state:=public.ep_snapshot();
  for p in select * from jsonb_to_recordset(p_state->'players') as x(
    id bigint,reg_number bigint,external_id text,code char(4),full_name text,email text,phone text,institution_type text,institution_name text,student_id text,
    has_online_rating boolean,online_rating integer,rating_platform text,rating_time_control text,level text,
    seed_rating integer,seed_source text,checked_in boolean,active boolean,consent boolean,created_at timestamptz,updated_at timestamptz,deleted_at timestamptz)
  loop
    insert into public.players(id,reg_number,external_id,code,full_name,email,phone,institution_type,institution_name,student_id,has_online_rating,online_rating,
      rating_platform,rating_time_control,level,seed_rating,seed_source,checked_in,active,consent,created_at,updated_at,deleted_at,elo,is_active,is_present)
    values(p.id,p.reg_number,p.external_id,p.code,p.full_name,p.email,p.phone,p.institution_type,p.institution_name,p.student_id,p.has_online_rating,p.online_rating,
      p.rating_platform,p.rating_time_control,p.level,p.seed_rating,p.seed_source,p.checked_in,p.active,p.consent,p.created_at,p.updated_at,p.deleted_at,p.seed_rating,p.active,p.checked_in)
    on conflict(id) do update set external_id=excluded.external_id,code=excluded.code,full_name=excluded.full_name,email=excluded.email,phone=excluded.phone,
      institution_type=excluded.institution_type,institution_name=excluded.institution_name,student_id=excluded.student_id,
      has_online_rating=excluded.has_online_rating,online_rating=excluded.online_rating,rating_platform=excluded.rating_platform,
      rating_time_control=excluded.rating_time_control,level=excluded.level,seed_rating=excluded.seed_rating,seed_source=excluded.seed_source,
      checked_in=excluded.checked_in,active=excluded.active,consent=excluded.consent,updated_at=excluded.updated_at,deleted_at=excluded.deleted_at,
      elo=excluded.elo,is_active=excluded.is_active,is_present=excluded.is_present;
  end loop;
  delete from public.games where id not in (select (g->>'id')::bigint from jsonb_array_elements(p_state->'games') g);
  delete from public.rounds where id not in (select (r->>'id')::bigint from jsonb_array_elements(p_state->'rounds') r);
  insert into public.rounds select * from jsonb_populate_recordset(null::public.rounds,p_state->'rounds') where true
  on conflict(id) do update set status=excluded.status,planned_start=excluded.planned_start,started_at=excluded.started_at,closed_at=excluded.closed_at,
    warnings=excluded.warnings,context=excluded.context,invalidated=excluded.invalidated;
  insert into public.games select * from jsonb_populate_recordset(null::public.games,p_state->'games') where true
  on conflict(id) do update set white_id=excluded.white_id,black_id=excluded.black_id,table_number=excluded.table_number,result=excluded.result,
    is_forfeit=excluded.is_forfeit,notes=excluded.notes,pgn=excluded.pgn,moves_count=excluded.moves_count,finished_at=excluded.finished_at,
    entered_by=excluded.entered_by,updated_at=excluded.updated_at,tie_context=excluded.tie_context;
  update public.tournament_settings set revision=revision+1,value=p_state->'settings' where singleton;
  insert into public.audit_log(actor,action,old_value,new_value) values(p_actor,p_action,old_state,public.ep_snapshot());
  return actual+1;
end $$;

create function public.ep_rate(p_key text,p_limit integer,p_seconds integer,p_fail boolean default false,p_reset boolean default false)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare r public.request_limits; begin
  insert into public.request_limits(key) values(p_key) on conflict do nothing;
  select * into r from public.request_limits where key=p_key for update;
  if p_reset then r.failures=0; r.blocked_until=null; r.window_start=clock_timestamp();
  elsif r.blocked_until>clock_timestamp() then
    return jsonb_build_object('blocked',true,'retry_after',ceil(extract(epoch from r.blocked_until-clock_timestamp())));
  else
    if r.window_start+make_interval(secs=>p_seconds)<=clock_timestamp() then r.failures=0;r.window_start=clock_timestamp();r.blocked_until=null;end if;
    if p_fail then
      r.failures=r.failures+1;
      if r.failures>=p_limit then r.blocked_until=clock_timestamp()+make_interval(secs=>p_seconds);end if;
    end if;
  end if;
  update public.request_limits set failures=r.failures,window_start=r.window_start,blocked_until=r.blocked_until where key=p_key;
  delete from public.request_limits where window_start<clock_timestamp()-interval '1 day' and (blocked_until is null or blocked_until<clock_timestamp());
  return jsonb_build_object('blocked',coalesce(r.blocked_until>clock_timestamp(),false),'retry_after',case when r.blocked_until>clock_timestamp() then p_seconds else 0 end);
end $$;
-- Browser access is denied; only server-side service-role RPCs access private tables.
do $$ declare t text; begin
  foreach t in array array['players','matches','rounds','games','round_participants','tournament_settings','audit_log','request_limits'] loop
    execute format('alter table public.%I enable row level security',t);
    execute format('revoke all on public.%I from public,anon,authenticated',t);
  end loop;
end $$;
revoke all on function public.ep_snapshot(),public.ep_commit(bigint,jsonb,text,text),public.ep_rate(text,integer,integer,boolean,boolean) from public,anon,authenticated;
grant execute on function public.ep_snapshot(),public.ep_commit(bigint,jsonb,text,text),public.ep_rate(text,integer,integer,boolean,boolean) to service_role;
commit;
