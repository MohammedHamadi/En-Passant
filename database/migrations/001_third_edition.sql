-- Legacy records receive secure random codes without inventing missing contact data.
do $$ declare p record; candidate text; attempt integer; begin
  for p in select id from public.players where code is null loop
    for attempt in 1..20 loop
      candidate := (1000 + (('x'||substr(replace(gen_random_uuid()::text,'-',''),1,8))::bit(32)::bigint % 9000))::text;
      begin update public.players set code=candidate where id=p.id; exit;
      exception when unique_violation then
        if attempt=20 then raise exception 'Code exhaustion for legacy player %. Retry migration.',p.id; end if;
      end;
    end loop;
  end loop;
end $$;
alter table public.players alter column code set not null;

create table public.rounds (
  id bigint generated by default as identity primary key,
  number integer not null unique check(number>0),
  stage text not null check(stage in ('swiss','knockout')),
  status text not null check(status in ('draft','published','running','closed')),
  duration_minutes integer not null default 30 check(duration_minutes between 1 and 180),
  planned_start timestamptz,started_at timestamptz,closed_at timestamptz,
  warnings jsonb not null default '[]',context text,invalidated boolean not null default false
);
create table public.games (
  id bigint generated by default as identity primary key,
  round_id bigint not null references public.rounds(id) on delete restrict,
  white_id bigint not null references public.players(id) on delete restrict,
  black_id bigint references public.players(id) on delete restrict,
  table_number integer check(table_number>0),
  kind text not null check(kind in ('swiss','knockout','armageddon')),
  result text check(result in ('white','black','draw','bye','double_forfeit')),
  is_forfeit boolean not null default false,
  notes text,pgn text,moves_count integer check(moves_count>=0),
  finished_at timestamptz,entered_by text,updated_at timestamptz not null default now(),tie_context text,
  check(white_id is distinct from black_id),
  check((black_id is null and result='bye' and table_number is null and kind='swiss') or
        (black_id is not null and (result is null or result<>'bye'))),
  check(kind='armageddon' or black_id is null or table_number is not null),
  check(not is_forfeit or result in ('white','black','double_forfeit'))
);
create unique index games_round_table_unique on public.games(round_id,table_number) where kind<>'armageddon';
create table public.round_participants (
  round_id bigint not null references public.rounds(id),
  player_id bigint not null references public.players(id),
  game_id bigint not null references public.games(id) on delete cascade,
  primary key(round_id,player_id) deferrable initially deferred
);
create function public.ep_participants() returns trigger language plpgsql set search_path=public,pg_temp as $$ begin
  delete from public.round_participants where game_id=new.id;
  if new.kind<>'armageddon' then
    insert into public.round_participants values(new.round_id,new.white_id,new.id);
    if new.black_id is not null then insert into public.round_participants values(new.round_id,new.black_id,new.id); end if;
  end if;
  return new;
end $$;
create trigger ep_game_participants after insert or update on public.games for each row execute function public.ep_participants();

insert into public.rounds(id,number,stage,status,duration_minutes,closed_at)
select round_number,round_number,'swiss',
  case when bool_and(white_score is not null and (black_player_id is null or black_score is not null)) then 'closed' else 'published' end,
  30,case when bool_and(white_score is not null and (black_player_id is null or black_score is not null)) then max(updated_at) else null end
from public.matches group by round_number;
insert into public.games(id,round_id,white_id,black_id,table_number,kind,result,is_forfeit,finished_at,updated_at)
select id,round_number,white_player_id,black_player_id,
  case when black_player_id is null then null else row_number() over(partition by round_number order by is_bye,id)::integer end,
  'swiss',case when black_player_id is null then 'bye' when white_score is null or black_score is null then null
    when white_bye and black_bye then 'double_forfeit' when white_score>black_score then 'white' when white_score<black_score then 'black' else 'draw' end,
  black_player_id is not null and (white_bye or black_bye),
  case when white_score is not null then updated_at else null end,updated_at from public.matches;

